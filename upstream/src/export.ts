import { existsSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

import { git } from "./exec.ts";
import { patchFiles, readPatchCommits } from "./patches.ts";
import { checkoutDir, patchesDir, type UpstreamPin, upstreamDir } from "./pin.ts";

/** Writes the commits on the checkout's `offload` branch to patches/ and regenerates PATCHES.md from their messages. */
export const exportPatches = ({ commit, tag }: Pick<UpstreamPin, "commit" | "tag">) => {
  for (const marker of ["rebase-apply", "rebase-merge", "CHERRY_PICK_HEAD"]) {
    if (existsSync(path.join(checkoutDir, ".git", marker))) {
      throw new Error(`upstream/payload has an unfinished ${marker}. Finish or abort it first.`);
    }
  }

  for (const file of patchFiles()) rmSync(file);
  git([
    "format-patch",
    "--zero-commit",
    "--no-signature",
    "--no-numbered",
    "--output-directory",
    patchesDir,
    `${commit}..offload`,
  ]);

  const commits = readPatchCommits({ base: commit, head: "offload" });

  const ledger = [
    "# Offload patches",
    "",
    `Generated by \`pnpm upstream:export\` from the commit messages on top of Payload ${tag}. Edit the commits, not this file.`,
    "",
    "| # | Patch | Upstream | Drop when |",
    "| --- | --- | --- | --- |",
    ...commits.map(
      (patch, index) =>
        `| ${index + 1} | \`${patch.id}\` | ${patch.upstream ?? "Not proposed"} | ${patch.dropWhen} |`,
    ),
    "",
    ...commits.flatMap((patch, index) => [
      `## ${index + 1}. ${patch.subject}`,
      "",
      patch.intent,
      "",
      `Tests: ${patch.tests}`,
      "",
    ]),
  ].join("\n");

  writeFileSync(path.join(upstreamDir, "PATCHES.md"), ledger);
  console.log(`Exported ${commits.length} patch(es) to upstream/patches and upstream/PATCHES.md.`);
};

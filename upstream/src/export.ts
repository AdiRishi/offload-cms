import { existsSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

import rootManifest from "../../package.json" with { type: "json" };
import { git } from "./exec.ts";
import { type PatchCommit, patchFiles, readPatchCommits } from "./patches.ts";
import { checkoutDir, patchesDir, type UpstreamPin, upstreamDir } from "./pin.ts";

/** One docs page per patch, generated from its commit message. */
const patchPagesDir = path.resolve(upstreamDir, "../docs/content/patches");
const generatedPage = /^\d{4}-.+\.md$/;
const repositoryUrl = rootManifest.homepage.replace(/#readme$/, "");
const pullRequest = /^https:\/\/github\.com\/([^/]+\/[^/]+)\/pull\/(\d+)$/;
/** Commit messages are plain text, so `<x>` must not render as an HTML tag. */
const markdownText = (text: string) => text.replaceAll("<", "\\<");

const patchPage = (patch: PatchCommit, patchFile: string, tag: string) => {
  const title = patch.subject.replace(/^\w+(\([^)]*\))?!?:\s*/, "");
  const upstreamPr = patch.upstream === undefined ? null : pullRequest.exec(patch.upstream);
  const upstream =
    patch.upstream === undefined
      ? "Not proposed"
      : `[${upstreamPr ? `${upstreamPr[1]}#${upstreamPr[2]}` : patch.upstream}](${patch.upstream})`;

  return [
    "---",
    `title: ${JSON.stringify(title.charAt(0).toUpperCase() + title.slice(1))}`,
    `description: ${JSON.stringify(`Drop when ${patch.dropWhen}.`)}`,
    "---",
    "",
    `<!-- Generated by \`pnpm upstream export\` from the patch's commit message on top of Payload ${tag}. Edit the commit, not this page. -->`,
    "",
    markdownText(patch.intent),
    "",
    `- **Patch:** \`${patch.id}\`, committed as \`${patch.subject}\``,
    `- **Upstream:** ${upstream}`,
    `- **Tests:** \`${patch.tests}\``,
    `- **Diff:** [\`upstream/patches/${patchFile}\`](${repositoryUrl}/blob/main/upstream/patches/${patchFile})`,
    "",
  ].join("\n");
};

/** Writes the commits on the checkout's `offload` branch to patches/, and one docs page per patch from their messages. */
export const exportPatches = ({ commit, tag }: Pick<UpstreamPin, "commit" | "tag">) => {
  for (const marker of ["rebase-apply", "rebase-merge", "CHERRY_PICK_HEAD"]) {
    if (existsSync(path.join(checkoutDir, ".git", marker))) {
      throw new Error(`upstream/payload has an unfinished ${marker}. Finish or abort it first.`);
    }
  }

  for (const file of patchFiles()) rmSync(file);
  git([
    "format-patch",
    "--zero-commit",
    "--no-signature",
    "--no-numbered",
    "--output-directory",
    patchesDir,
    `${commit}..offload`,
  ]);

  const commits = readPatchCommits({ base: commit, head: "offload" });
  const files = patchFiles().map((file) => path.basename(file));

  for (const page of readdirSync(patchPagesDir).filter((file) => generatedPage.test(file))) {
    rmSync(path.join(patchPagesDir, page));
  }
  for (const [index, patch] of commits.entries()) {
    writeFileSync(
      path.join(patchPagesDir, `${String(index + 1).padStart(4, "0")}-${patch.id}.md`),
      patchPage(patch, files[index] ?? "", tag),
    );
  }

  console.log(`Exported ${commits.length} patch(es) to upstream/patches and docs/content/patches.`);
};

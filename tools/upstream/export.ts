// Writes the commits on vendor/payload's `offload` branch back to
// upstream/patches and regenerates upstream/PATCHES.md from their messages.
//
// usage: pnpm upstream:export

import { existsSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'

import { fail, patchesDir, readPin, upstreamDir, vendorDir, vendorGit } from '../lib.ts'
import { readPatchCommits } from './patches.ts'

const pin = readPin()

for (const marker of ['rebase-apply', 'rebase-merge', 'CHERRY_PICK_HEAD']) {
  if (existsSync(path.join(vendorDir, '.git', marker))) {
    fail(`vendor/payload has an unfinished ${marker}. Finish or abort it first.`)
  }
}

for (const file of readdirSync(patchesDir).filter((name) => name.endsWith('.patch'))) {
  rmSync(path.join(patchesDir, file))
}
vendorGit([
  'format-patch',
  '--zero-commit',
  '--no-signature',
  '--no-numbered',
  '--output-directory',
  patchesDir,
  `${pin.commit}..offload`,
])

const commits = readPatchCommits({ base: pin.commit, head: 'offload' })

const ledger = [
  '# Offload patches',
  '',
  `Generated by \`pnpm upstream:export\` from the commit messages on top of Payload ${pin.tag}. Edit the commits, not this file.`,
  '',
  '| # | Patch | Upstream | Drop when |',
  '| --- | --- | --- | --- |',
  ...commits.map(
    (commit, index) =>
      `| ${index + 1} | \`${commit.id}\` | ${commit.upstream ?? 'Not proposed'} | ${commit.dropWhen} |`,
  ),
  '',
  ...commits.flatMap((commit, index) => [
    `## ${index + 1}. ${commit.subject}`,
    '',
    commit.intent,
    '',
    `Tests: ${commit.tests}`,
    '',
  ]),
].join('\n')

writeFileSync(path.join(upstreamDir, 'PATCHES.md'), ledger)
console.log(`Exported ${commits.length} patch(es) to upstream/patches and upstream/PATCHES.md.`)
